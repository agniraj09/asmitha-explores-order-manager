-- ---------------------------------------------------------------- customers
create table if not exists customers (
    id                      bigint generated by default as identity,
    name                    varchar(120) not null,
    address                 text         not null,
    mobile_number           varchar(10)  not null,
    alternate_mobile_number varchar(10),
    primary key (id),
    constraint uk_customers_mobile_number unique (mobile_number)
);

-- Added later: safe to run against an existing customers table.
alter table customers add column if not exists alternate_mobile_number varchar(10);

-- ----------------------------------------------------------------- products
create table if not exists products (
    id                     bigint generated by default as identity,
    name                   varchar(150)   not null,
    category               varchar(40),
    price                  numeric(12, 2) not null,
    quantity_in_hand       integer        not null,
    quantity_to_be_ordered integer        not null,
    primary key (id)
);

-- ------------------------------------------------------------------- orders
create table if not exists orders (
    id                  bigint generated by default as identity,
    customer_id         bigint      not null,
    order_date          date        not null,
    order_status        varchar(30) not null,
    tracking_id         varchar(60),
    customization_notes text,
    primary key (id),
    constraint ck_orders_status check (
        order_status in ('NEW', 'PRINTING_IN_PROGRESS', 'PACKED', 'SHIPPED', 'DELIVERED')
    )
);

-- -------------------------------------------------------------- order_items
create table if not exists order_items (
    id                 bigint generated by default as identity,
    order_id           bigint         not null,
    product_id         bigint         not null,
    quantity           integer        not null,
    unit_price         numeric(12, 2) not null,
    shortfall_quantity integer,
    primary key (id)
);

-- ------------------------------------------------------------- foreign keys
do $$
begin
    if not exists (select 1 from pg_constraint where conname = 'fk_orders_customer') then
        alter table orders
            add constraint fk_orders_customer
            foreign key (customer_id) references customers (id);
    end if;

    if not exists (select 1 from pg_constraint where conname = 'fk_order_items_order') then
        alter table order_items
            add constraint fk_order_items_order
            foreign key (order_id) references orders (id);
    end if;

    if not exists (select 1 from pg_constraint where conname = 'fk_order_items_product') then
        alter table order_items
            add constraint fk_order_items_product
            foreign key (product_id) references products (id);
    end if;
end
$$;

-- ------------------------------------------------------------------ indexes
create index if not exists ix_orders_customer     on orders (customer_id);
create index if not exists ix_orders_status       on orders (order_status);
create index if not exists ix_orders_order_date   on orders (order_date);
create index if not exists ix_order_items_order   on order_items (order_id);
create index if not exists ix_order_items_product on order_items (product_id);
create index if not exists ix_products_category   on products (category);
create index if not exists ix_products_in_hand    on products (quantity_in_hand);

