-- ---------------------------------------------------------------- customers
create table if not exists customers (
    id                      bigint generated by default as identity,
    name                    varchar(120) not null,
    address                 text         not null,
    mobile_number           varchar(10)  not null,
    alternate_mobile_number varchar(10),
    primary key (id),
    constraint uk_customers_mobile_number unique (mobile_number)
);

-- Added later: safe to run against an existing customers table.
alter table customers add column if not exists alternate_mobile_number varchar(10);

-- ----------------------------------------------------------------- products
create table if not exists products (
    id                     bigint generated by default as identity,
    name                   varchar(150)   not null,
    category               varchar(40),
    price                  numeric(12, 2) not null,
    quantity_in_hand       integer        not null,
    quantity_to_be_ordered integer        not null,
    primary key (id)
);

-- ------------------------------------------------------------------- orders
create table if not exists orders (
    id                  bigint generated by default as identity,
    customer_id         bigint      not null,
    order_date          date        not null,
    order_status        varchar(30) not null,
    tracking_id         varchar(60),
    customization_notes text,
    special_notes        text,
    delivery_status_text varchar(120),
    tracking_checked_at  timestamp,
    delivered_on         date,
    primary key (id),
    constraint ck_orders_status check (
        order_status in ('NEW', 'PRINTING_IN_PROGRESS', 'PACKED', 'SHIPPED', 'DELIVERED')
    )
);

-- -------------------------------------------------------------- order_items
create table if not exists order_items (
    id                 bigint generated by default as identity,
    order_id           bigint         not null,
    product_id         bigint         not null,
    quantity           integer        not null,
    unit_price         numeric(12, 2) not null,
    shortfall_quantity integer,
    primary key (id)
);

-- -------------------------------------------------------- transaction tags
create table if not exists transaction_tags (
    id          bigint generated by default as identity,
    name        varchar(60) not null,
    color_hex   varchar(7),
    description varchar(200),
    primary key (id),
    constraint uk_transaction_tags_name unique (name)
);

-- ------------------------------------------------------------- transactions
-- The money book: income lines are created automatically for every order (and keep
-- order_id so they follow it), expenses are entered by hand.
create table if not exists transactions (
    id                bigint generated by default as identity,
    transaction_type  varchar(20)    not null,
    category          varchar(30)    not null,
    amount            numeric(12, 2) not null,
    transaction_date  date           not null,
    description       text,
    order_id          bigint,
    system_generated  boolean        not null default false,
    manually_adjusted boolean        not null default false,
    created_at        timestamp      not null default current_timestamp,
    primary key (id),
    constraint ck_transactions_type check (transaction_type in ('INCOME', 'EXPENSE')),
    constraint ck_transactions_category check (
        category in ('ORDER_SALE', 'OTHER_INCOME', 'PRINTING', 'PACKING',
                     'SHIPPING', 'TRANSPORT', 'MATERIALS', 'OTHER_EXPENSE')
    )
);

-- ------------------------------------------------- transaction <-> tag links
create table if not exists transaction_tag_links (
    transaction_id bigint not null,
    tag_id         bigint not null,
    primary key (transaction_id, tag_id)
);

-- ------------------------------------------------------------- foreign keys
do $$
begin
    -- Delivery detection columns, added after the first release.
    alter table orders add column if not exists delivery_status_text varchar(120);
    alter table orders add column if not exists tracking_checked_at  timestamp;
    alter table orders add column if not exists delivered_on         date;
    -- Owner-facing notes, added after the first release.
    alter table orders add column if not exists special_notes        text;

    if not exists (select 1 from pg_constraint where conname = 'fk_orders_customer') then
        alter table orders
            add constraint fk_orders_customer
            foreign key (customer_id) references customers (id);
    end if;

    if not exists (select 1 from pg_constraint where conname = 'fk_order_items_order') then
        alter table order_items
            add constraint fk_order_items_order
            foreign key (order_id) references orders (id);
    end if;

    if not exists (select 1 from pg_constraint where conname = 'fk_order_items_product') then
        alter table order_items
            add constraint fk_order_items_product
            foreign key (product_id) references products (id);
    end if;

    if not exists (select 1 from pg_constraint where conname = 'fk_transactions_order') then
        alter table transactions
            add constraint fk_transactions_order
            foreign key (order_id) references orders (id);
    end if;

    if not exists (select 1 from pg_constraint where conname = 'fk_transaction_tag_links_transaction') then
        alter table transaction_tag_links
            add constraint fk_transaction_tag_links_transaction
            foreign key (transaction_id) references transactions (id);
    end if;

    if not exists (select 1 from pg_constraint where conname = 'fk_transaction_tag_links_tag') then
        alter table transaction_tag_links
            add constraint fk_transaction_tag_links_tag
            foreign key (tag_id) references transaction_tags (id);
    end if;
end
$$;

-- ------------------------------------------------------------------ indexes
create index if not exists ix_orders_customer     on orders (customer_id);
create index if not exists ix_orders_status       on orders (order_status);
create index if not exists ix_orders_order_date   on orders (order_date);
create index if not exists ix_order_items_order   on order_items (order_id);
create index if not exists ix_order_items_product on order_items (product_id);
create index if not exists ix_products_category   on products (category);
create index if not exists ix_products_in_hand    on products (quantity_in_hand);
create index if not exists ix_transactions_date   on transactions (transaction_date);
create index if not exists ix_transactions_type   on transactions (transaction_type);
create index if not exists ix_transactions_order  on transactions (order_id);
create index if not exists ix_tag_links_tag       on transaction_tag_links (tag_id);

